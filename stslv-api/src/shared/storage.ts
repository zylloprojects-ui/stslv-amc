import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Where attachment files live. The database holds only the metadata and a
 * generated key, so a different store (object storage) can replace this one
 * without changing the business model. Two stores exist: a local folder
 * (LocalDiskStorage, development and tests) and a private Cloudflare R2 bucket
 * (R2Storage in r2-storage.ts, production). Files are only ever served through
 * the API, after its permission checks: no store hands out public links.
 */
export interface FileStorage {
  put(key: string, data: Buffer): Promise<void>;
  /** The file's content. Throws StoredFileNotFoundError when the store has no such file; any other error means the store could not be read. */
  get(key: string): Promise<Buffer>;
  /** Removes a file this application stored but never recorded (a failed save). Optional: a store without it keeps the file. */
  remove?(key: string): Promise<void>;
}

/** The store was reached and has no file under the key. */
export class StoredFileNotFoundError extends Error {
  constructor(key: string) {
    super(`No stored file under key ${key}.`);
    this.name = "StoredFileNotFoundError";
  }
}

// Keys are generated by the application ("<uuid>.<ext>"); anything else is refused, so a key can never reach outside the folder or prefix.
const KEY_PATTERN = /^[0-9a-f-]{36}\.(pdf|png|jpg|doc|docx)$/;

/** Throws unless the key is one this application generates. Every store checks it before any read or write. */
export function assertStorageKey(key: string): void {
  if (!KEY_PATTERN.test(key)) {
    throw new Error("Invalid storage key.");
  }
}

/** Files in one local folder, outside the web root. For local development and tests. */
export class LocalDiskStorage implements FileStorage {
  constructor(private readonly root: string) {}

  private pathOf(key: string): string {
    assertStorageKey(key);

    return path.join(this.root, key);
  }

  async put(key: string, data: Buffer): Promise<void> {
    await mkdir(this.root, { recursive: true });
    // "wx": never overwrite an existing file.
    await writeFile(this.pathOf(key), data, { flag: "wx" });
  }

  async get(key: string): Promise<Buffer> {
    try {
      return await readFile(this.pathOf(key));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") {
        throw new StoredFileNotFoundError(key);
      }
      throw error;
    }
  }

  async remove(key: string): Promise<void> {
    await rm(this.pathOf(key), { force: true });
  }
}
